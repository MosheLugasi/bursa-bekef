export function stationIndex(id: string): number {
  return JOURNEY.findIndex((s) => s.id === id);
}

/** סדר קבוע ומעורבב לתשובות של כל שאלה – כדי שהתשובה הנכונה לא תהיה תמיד ראשונה */
export function answerOrder(q: JourneyQuestion): number[] {
  let h = 2166136261;
  for (const ch of q.q) h = Math.imul(h ^ ch.charCodeAt(0), 16777619) >>> 0;
  const idx = q.options.map((_, i) => i);
  for (let i = idx.length - 1; i > 0; i--) {
    h = (Math.imul(h, 1103515245) + 12345) >>> 0;
    const j = (h >>> 8) % (i + 1);
    [idx[i], idx[j]] = [idx[j], idx[i]];
  }
  return idx;
}

export type StickerKind = 'none' | 'normal' | 'gold';

/** מצב המדבקה של תחנה: אין / רגילה / זהב (3 כוכבים) */
export function stickerKind(journey: Record<string, { stars: number }> | undefined, id: string): StickerKind {
  const r = journey?.[id];
  return !r ? 'none' : r.stars >= 3 ? 'gold' : 'normal';
}

/** כמה תיבות אוצר כבר הרווחתם לפי מספר התחנות שהושלמו */
export function chestsEarned(done: number): number {
  return Math.floor(done / CHEST_EVERY);
}

